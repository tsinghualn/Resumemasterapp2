// Common parsing issue keywords and patterns for categorization
const ISSUE_PATTERNS: Record<string, string[]> = {
  dates: ['missing date', 'wrong date', 'incorrect date', 'date error', 'date parse', 'dates are wrong', 'no dates'],
  company: ['wrong company', 'company name', 'missing company', 'incorrect company', 'employer name', 'organization'],
  skills: ['wrong skill', 'missing skill', 'skill error', 'incorrect skills', 'skills not', 'lost skills'],
  contact: ['email error', 'phone error', 'contact info', 'missing contact', 'phone number', 'email address', 'linkedin'],
  title: ['wrong title', 'job title', 'incorrect title', 'position title', 'role name'],
  bullets: ['missing bullet', 'lost information', 'truncated', 'incomplete', 'missing content', 'lost data'],
  order: ['wrong order', 'chronological', 'sorting', 'order error', 'sequence', 'not sorted'],
  name: ['name error', 'wrong name', 'missing name', 'name format', 'full name'],
  education: ['GPA missing', 'GPA wrong', 'degree error', 'university', 'graduation', 'school name'],
  projects: ['project missing', 'lost project', 'project not'],
  certifications: ['certification missing', 'cert not', 'license'],
  awards: ['award missing', 'honor not', 'achievement'],
  whitespace: ['extra space', 'spacing', 'whitespace', 'double space', 'spacing issue'],
  duplicates: ['duplicate', 'repeated', 'duplicated', 'twice', 'multiple times']
};

// Categorize feedback comments by issue type
function categorizeFeedbackComments(comments: string[]): Record<string, string[]> {
  const categorized: Record<string, string[]> = {};
  
  comments.forEach(comment => {
    const lowerComment = comment.toLowerCase();
    
    for (const [category, keywords] of Object.entries(ISSUE_PATTERNS)) {
      if (keywords.some(keyword => lowerComment.includes(keyword))) {
        if (!categorized[category]) {
          categorized[category] = [];
        }
        categorized[category].push(comment);
      }
    }
  });
  
  return categorized;
}

// Analyze feedback using OpenAI
async function analyzeFeedbackWithAI(negativeComments: string[], positiveComments: string[]): Promise<any> {
  const openaiKey = Deno.env.get('OPENAI_API_KEY');
  
  if (!openaiKey) {
    throw new Error('OPENAI_API_KEY not configured');
  }

    const negativeList = negativeComments.length > 0
      ? negativeComments.map((comment, i) => `${i + 1}. ${comment}`).join('\n')
      : 'None';

    const positiveList = positiveComments.length > 0
      ? positiveComments.map((comment, i) => `${i + 1}. ${comment}`).join('\n')
      : 'None';

    const prompt = `You are a feedback analyzer for a resume parsing AI system. Below are negative and positive feedback comments from users about parsing issues.

Your task:
1. Identify recurring themes and common parsing issues.
2. Categorize issues (e.g., "missing dates", "incorrect company names", "wrong skills", "contact info errors", etc.).
3. Count frequency of each issue type.
4. Suggest specific improvements to the parsing prompt.
5. Provide updated prompt instructions to fix these issues.
6. Highlight the parsing behaviors that worked well (use the positive feedback comments).

Negative feedback comments:
${negativeList}

Positive feedback comments:
${positiveList}

Respond with JSON in this format:
{
  "total_feedback_analyzed": number,
  "common_issues": [
    {
      "category": "issue category name",
      "count": number,
      "severity": "high" | "medium" | "low",
      "examples": ["example feedback 1", "example feedback 2"],
      "keywords": ["keyword1", "keyword2"]
    }
  ],
  "recommendations": [
    {
      "issue": "issue description",
      "current_problem": "what's going wrong",
      "suggested_fix": "specific prompt instruction to add"
    }
  ],
  "summary": "brief summary of main issues and fixes"
}`;

  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${openaiKey}`,
    },
    body: JSON.stringify({
      model: 'gpt-4o-mini',
      messages: [
        {
          role: 'system',
          content: 'You are an expert at analyzing user feedback and improving AI prompts for resume parsing. Always respond with valid JSON.'
        },
        {
          role: 'user',
          content: prompt
        }
      ],
      response_format: { type: 'json_object' },
      temperature: 0.3,
    }),
  });

  if (!response.ok) {
    const error = await response.text();
    throw new Error(`OpenAI API error: ${error}`);
  }

  const data = await response.json();
  const analysis = JSON.parse(data.choices[0].message.content);
  
  return analysis;
}

// Store analysis in the relational tables
async function storeAnalysisInTables(
  analysisDate: string,
  feedbackCount: number,
  commentsAnalyzed: number,
  analysis: any
): Promise<string | null> {
  try {
    // 1. Insert into feedback_analyses table
    const { data: analysisRecord, error: analysisError } = await supabase
      .from('feedback_analyses')
      .upsert({
        analysis_date: analysisDate,
        feedback_count: feedbackCount,
        comments_analyzed: commentsAnalyzed,
        summary: analysis.summary || '',
        status: 'pending_review'
      }, {
        onConflict: 'analysis_date'
      })
      .select('id')
      .single();

    if (analysisError) {
      console.error('❌ Error storing analysis:', analysisError);
      return null;
    }

    const analysisId = analysisRecord.id;
    console.log('✅ Analysis stored with ID:', analysisId);

    // 2. Delete existing common issues and recommendations for this analysis (in case of re-run)
    await supabase
      .from('analysis_common_issues')
      .delete()
      .eq('analysis_id', analysisId);

    await supabase
      .from('analysis_recommendations')
      .delete()
      .eq('analysis_id', analysisId);

    // 3. Insert common issues
    const commonIssues = analysis.common_issues || [];
    if (commonIssues.length > 0) {
      const issuesToInsert = commonIssues.map((issue: any) => ({
        analysis_id: analysisId,
        category: issue.category,
        count: issue.count,
        severity: issue.severity || 'medium',
        keywords: issue.keywords || [],
        examples: issue.examples || []
      }));

      const { error: issuesError } = await supabase
        .from('analysis_common_issues')
        .insert(issuesToInsert);

      if (issuesError) {
        console.error('❌ Error storing common issues:', issuesError);
      } else {
        console.log(`✅ Stored ${issuesToInsert.length} common issues`);
      }
    }

    // 4. Insert recommendations
    const recommendations = analysis.recommendations || [];
    if (recommendations.length > 0) {
      const recsToInsert = recommendations.map((rec: any) => ({
        analysis_id: analysisId,
        issue: rec.issue,
        current_problem: rec.current_problem,
        suggested_fix: rec.suggested_fix
      }));

      const { error: recsError } = await supabase
        .from('analysis_recommendations')
        .insert(recsToInsert);

      if (recsError) {
        console.error('❌ Error storing recommendations:', recsError);
      } else {
        console.log(`✅ Stored ${recsToInsert.length} recommendations`);
      }
    }

    return analysisId;
  } catch (error) {
    console.error('❌ Error in storeAnalysisInTables:', error);
    return null;
  }
}

// Run feedback analysis endpoint
app.post("/make-server-bc1c5df9/run-feedback-analysis", async (c) => {
  try {
    const { daysBack = 1 } = await c.req.json().catch(() => ({ daysBack: 1 }));
    
    console.log(`🕐 Starting feedback analysis for last ${daysBack} day(s) at`, new Date().toISOString());

    // Get feedback from the specified period
    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - daysBack);

    const { data: feedbackData, error: fetchError } = await supabase
      .from('resume_feedback')
      .select('*')
      .gte('created_at', cutoffDate.toISOString())
      .order('created_at', { ascending: false });

    if (fetchError) {
      console.error('❌ Error fetching feedback:', fetchError);
      return c.json({ error: 'Failed to fetch feedback', details: fetchError.message }, 500);
    }

    if (!feedbackData || feedbackData.length === 0) {
      console.log('ℹ️ No feedback in the specified period');
      
      return c.json({ 
        success: true, 
        message: `No feedback to analyze in the last ${daysBack} day(s)`,
        analyzed_count: 0 
      });
    }

    const negativeFeedback = feedbackData.filter((f: any) => !f.is_positive);
    const positiveFeedback = feedbackData.filter((f: any) => f.is_positive);

    const negativeComments = negativeFeedback
      .map((f: any) => f.comment)
      .filter((comment: string | null) => comment && comment.trim().length > 0);

    const positiveComments = positiveFeedback
      .map((f: any) => f.comment)
      .filter((comment: string | null) => comment && comment.trim().length > 0);

    const combinedComments = [...negativeComments, ...positiveComments];

    if (combinedComments.length === 0) {
      console.log('ℹ️ No comments to analyze (feedback contained only thumbs up/down)');
      
      return c.json({ 
        success: true, 
        message: 'No comments to analyze (feedback contained no text)',
        analyzed_count: 0,
        feedback_count: feedbackData.length
      });
    }

    console.log(`📊 Found ${feedbackData.length} feedback entries (${negativeComments.length} negative, ${positiveComments.length} positive)`);
    console.log(`💬 Analyzing ${combinedComments.length} feedback comments with AI...`);

    // Pre-categorize feedback by keywords (negative only)
    const categorized = categorizeFeedbackComments(negativeComments);
    const categorySummary = Object.entries(categorized)
      .map(([category, items]) => `${category}: ${items.length} issues`)
      .join(', ');
    
    console.log(`📋 Keyword-based categorization: ${categorySummary}`);

    // Analyze with OpenAI
    const analysis = await analyzeFeedbackWithAI(negativeComments, positiveComments);

    console.log('✅ AI Analysis complete:', analysis.summary);

    // Store in the relational tables
    const analysisDate = new Date().toISOString().split('T')[0];

    const analysisId = await storeAnalysisInTables(
      analysisDate,
      feedbackData.length,
      combinedComments.length,
      analysis
    );

    if (!analysisId) {
      console.error('❌ Failed to store analysis in tables');
      return c.json({ 
        error: 'Failed to store analysis',
        details: 'Database insert failed'
      }, 500);
    }

    console.log('💾 Analysis stored with ID:', analysisId);

    // Return the analysis
    return c.json({
      success: true,
      message: 'Feedback analysis completed successfully',
      analysis_id: analysisId,
      feedback_analyzed: feedbackData.length,
      comments_analyzed: combinedComments.length,
      summary: analysis.summary,
      common_issues_count: analysis.common_issues?.length || 0,
      recommendations_count: analysis.recommendations?.length || 0,
      positive_feedback_count: positiveComments.length,
      positive_examples: positiveComments.slice(0, 3)
    });

  } catch (error) {
    console.error('❌ Error in feedback analysis:', error);
    
    return c.json({
      error: 'Failed to analyze feedback',
      details: error instanceof Error ? error.message : 'Unknown error'
    }, 500);
  }
});

