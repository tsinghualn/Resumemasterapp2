// Get feedback statistics and success rates
app.get("/make-server-bc1c5df9/feedback-stats", async (c) => {
  try {
    const { daysBack = 30 } = c.req.query();
    
    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - parseInt(daysBack as string));

    const { data: feedbackData, error } = await supabase
      .from('resume_feedback')
      .select('is_positive, section_type, created_at')
      .gte('created_at', cutoffDate.toISOString());

    if (error) {
      return c.json({ error: 'Failed to fetch feedback', details: error.message }, 500);
    }

    if (!feedbackData || feedbackData.length === 0) {
      return c.json({ 
        success: true,
        stats: {
          total: 0,
          positive: 0,
          negative: 0,
          success_rate: 0,
          by_section: {}
        }
      });
    }

    const total = feedbackData.length;
    const positive = feedbackData.filter(f => f.is_positive).length;
    const negative = total - positive;
    const successRate = (positive / total) * 100;

    // Stats by section
    const bySection: Record<string, { total: number; positive: number; negative: number; success_rate: number }> = {};
    
    feedbackData.forEach(f => {
      const section = f.section_type || 'unknown';
      if (!bySection[section]) {
        bySection[section] = { total: 0, positive: 0, negative: 0, success_rate: 0 };
      }
      bySection[section].total++;
      if (f.is_positive) {
        bySection[section].positive++;
      } else {
        bySection[section].negative++;
      }
    });

    // Calculate success rates
    Object.keys(bySection).forEach(section => {
      bySection[section].success_rate = 
        (bySection[section].positive / bySection[section].total) * 100;
    });

    return c.json({ 
      success: true,
      stats: {
        total,
        positive,
        negative,
        success_rate: Math.round(successRate * 100) / 100,
        by_section: bySection,
        period_days: parseInt(daysBack as string)
      }
    });
  } catch (error) {
    console.error('Error fetching feedback stats:', error);
    return c.json({ 
      error: 'Server error',
      details: error instanceof Error ? error.message : 'Unknown error'
    }, 500);
  }
});

