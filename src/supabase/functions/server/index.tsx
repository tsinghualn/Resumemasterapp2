// Calculate and store current improvement metrics
app.post("/make-server-bc1c5df9/calculate-improvement", async (c) => {
  try {
    const { daysBack = 7 } = await c.req.json();

    console.log(`📊 Calculating improvement metrics for last ${daysBack} days...`);

    // Get the last applied analysis date from feedback_analyses table
    const { data: guidanceData } = await supabase
      .from('feedback_analyses')
      .select('applied_at')
      .eq('status', 'applied')
      .order('applied_at', { ascending: false })
      .limit(1)
      .single();

    let guidanceAppliedDate: Date;
    
    if (guidanceData?.applied_at) {
      guidanceAppliedDate = new Date(guidanceData.applied_at);
    } else {
      // If no guidance applied yet, use 7 days ago as baseline
      guidanceAppliedDate = new Date();
      guidanceAppliedDate.setDate(guidanceAppliedDate.getDate() - daysBack);
    }

    // Get feedback before guidance
    const beforeStart = new Date(guidanceAppliedDate);
    beforeStart.setDate(beforeStart.getDate() - daysBack);
    
    const { data: beforeFeedback } = await supabase
      .from('resume_feedback')
      .select('is_positive')
      .gte('created_at', beforeStart.toISOString())
      .lt('created_at', guidanceAppliedDate.toISOString());

    // Get feedback after guidance
    const afterEnd = new Date();
    
    const { data: afterFeedback } = await supabase
      .from('resume_feedback')
      .select('is_positive')
      .gte('created_at', guidanceAppliedDate.toISOString())
      .lte('created_at', afterEnd.toISOString());

    if (!beforeFeedback || !afterFeedback || beforeFeedback.length === 0 || afterFeedback.length === 0) {
      return c.json({ 
        success: false,
        message: 'Insufficient data to calculate improvement metrics',
        details: `Before: ${beforeFeedback?.length || 0}, After: ${afterFeedback?.length || 0}`
      });
    }

    // Calculate metrics
    const beforeTotal = beforeFeedback.length;
    const beforeNegative = beforeFeedback.filter(f => !f.is_positive).length;
    const beforeSuccessRate = ((beforeTotal - beforeNegative) / beforeTotal) * 100;

    const afterTotal = afterFeedback.length;
    const afterNegative = afterFeedback.filter(f => !f.is_positive).length;
    const afterSuccessRate = ((afterTotal - afterNegative) / afterTotal) * 100;

    const improvement = afterSuccessRate - beforeSuccessRate;

    const dateMeasured = new Date().toISOString().split('T')[0];

    // Store metrics in the new improvement_metrics table
    const { error: insertError } = await supabase
      .from('improvement_metrics')
      .upsert({
        date_measured: dateMeasured,
        guidance_applied_date: guidanceAppliedDate.toISOString().split('T')[0],
        before_total_feedback: beforeTotal,
        before_negative_feedback: beforeNegative,
        before_success_rate: Math.round(beforeSuccessRate * 100) / 100,
        after_total_feedback: afterTotal,
        after_negative_feedback: afterNegative,
        after_success_rate: Math.round(afterSuccessRate * 100) / 100,
        improvement_percentage: Math.round(improvement * 100) / 100
      }, {
        onConflict: 'date_measured'
      });

    if (insertError) {
      console.error('Error storing metrics:', insertError);
    }

    const metrics = {
      before_application: {
        total_feedback: beforeTotal,
        negative_feedback: beforeNegative,
        success_rate: Math.round(beforeSuccessRate * 100) / 100
      },
      after_application: {
        total_feedback: afterTotal,
        negative_feedback: afterNegative,
        success_rate: Math.round(afterSuccessRate * 100) / 100
      },
      improvement_percentage: Math.round(improvement * 100) / 100,
      guidance_applied_date: guidanceAppliedDate.toISOString(),
      calculated_at: new Date().toISOString()
    };

    console.log('✅ Improvement metrics calculated:', metrics);

    return c.json({ 
      success: true, 
      metrics
    });
  } catch (error) {
    console.error('Error calculating improvement:', error);
    return c.json({ 
      error: 'Failed to calculate improvement',
      details: error instanceof Error ? error.message : 'Unknown error'
    }, 500);
  }
});

